# -*- coding: utf-8 -*-
"""
Аналитическое решение кубического уравнения методом Кардано
(тригонометрическая форма для случая трёх различных действительных корней),
в точности по схеме из методических материалов:

    a*x^3 + b*x^2 + c*x + d = 0

Приведение к канонической (неполной) форме заменой y = x + b/(3a):

    y^3 + 3*p*y + 2*q = 0

где
    2*q = 2*b^3/(27*a^3) - b*c/(3*a^2) + d/a
    3*p = c/a - b^2/(3*a^2)

Если дискриминант D = q^2 + p^3 < 0, то все три корня действительны и различны.
Обозначим  r = sign(q) * sqrt(-p)   (т.к. p < 0),   cos(phi) = q / r^3.

    y1 = -2*r*cos(phi/3)
    y2 =  2*r*cos(pi/3 - phi/3)
    y3 =  2*r*cos(pi/3 + phi/3)

Возврат к исходной переменной: x_k = y_k - b/(3a).
"""
import numpy as np


def solve_cubic_cardano(a, b, c, d, tol=1e-12):
    """
    Решает a*x^3+b*x^2+c*x+d=0 методом Кардано (случай трёх действ. корней).
    Возвращает отсортированный список из 3 действительных корней.
    Бросает ValueError, если корни не все действительны (D > 0).
    """
    if abs(a) < tol:
        raise ValueError("a должно быть отлично от нуля (кубическое уравнение)")

    # Приведение к неполной (депрессированной) форме y^3 + 3*p*y + 2*q = 0
    # заменой  x = y - b/(3a)  (т.е.  y = x + b/(3a) ), где p, q — величины
    # из методических указаний:
    #   3p = c/a - b^2/(3a^2)         =>   p = c/(3a) - b^2/(9a^2)
    #   2q = 2b^3/(27a^3) - bc/(3a^2) + d/a
    p = c / (3.0 * a) - b ** 2 / (9.0 * a ** 2)
    q = (b ** 3) / (27.0 * a ** 3) - (b * c) / (6.0 * a ** 2) + d / (2.0 * a)
    # тогда депрессированное уравнение: y^3 + 3*p*y + 2*q = 0
    D = q ** 2 + p ** 3  # знак дискриминанта (D<0 <=> 3 действ. различных корня)

    if D > tol:
        raise ValueError(f"Дискриминант D={D} > 0: уравнение имеет один "
                          f"действительный и два комплексных корня.")

    if p > 0:
        # для нашей задачи (узлы Гаусса) должно быть p<0; подстрахуемся
        raise ValueError(f"p={p} >= 0: тригонометрическая формула Кардано "
                          f"(случай 3 действ. корней) неприменима.")

    r = np.sqrt(-p)
    if q < 0:
        r = -r
    # cos(phi) = q / r^3, с ограничением диапазона от ошибок округления
    cos_phi = np.clip(q / r ** 3, -1.0, 1.0)
    phi = np.arccos(cos_phi)

    y1 = -2.0 * r * np.cos(phi / 3.0)
    y2 = 2.0 * r * np.cos(np.pi / 3.0 - phi / 3.0)
    y3 = 2.0 * r * np.cos(np.pi / 3.0 + phi / 3.0)

    shift = b / (3.0 * a)
    roots = sorted([y1 - shift, y2 - shift, y3 - shift])
    return roots
